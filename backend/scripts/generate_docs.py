#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Генерация документов поставки из кода (п.15, позиция 5).

Словарь полей и матрица ролей берутся из самого приложения, а не из рукописи.
Иначе документация неизбежно расходится с системой при первом же изменении
обязательности поля — а именно на это поле опираются пользователи при работе.

    python backend/scripts/generate_docs.py

Результат:
    docs/СЛОВАРЬ-ПОЛЕЙ.md
    docs/МАТРИЦА-РОЛЕЙ.md
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "backend"))

DOCS = ROOT / "docs"

REQUIRED_TITLES = {
    "О": "обязательное",
    "У": "условно обязательное",
    "Н": "необязательное",
    "А": "формируется автоматически",
    "О/У": "обязательное / условно обязательное",
    "—": "—",
}

SECTION_ORDER = [
    "Паспорт", "Научное содержание", "Контрольные точки", "Результаты",
    "Публикация", "Связанные записи",
]

HEADER = """<!--
  ФАЙЛ СОЗДАН АВТОМАТИЧЕСКИ: python backend/scripts/generate_docs.py
  Правьте domain/validation.py, а не этот файл.
-->

"""


def field_dictionary_doc() -> str:
    from app.domain.validation import dictionary_document

    fields = dictionary_document()
    by_section: dict[str, list[dict]] = {}
    for item in fields:
        by_section.setdefault(item["section"], []).append(item)

    out = [HEADER]
    out.append("# Словарь полей электронной карточки проекта\n\n")
    out.append("Приложение А технического задания версии 1.0 от 06.10.2026.\n\n")
    out.append("Обозначения обязательности: **О** — обязательное, "
               "**У** — условно обязательное, **Н** — необязательное, "
               "**А** — формируется автоматически.\n\n")
    out.append("Столбцы **Упрощённый** и **Полный** — разные наборы требований "
               "для двух маршрутов. Столбец **Открыто** означает, что поле может "
               "быть передано в публичный раздел — но только после отдельного "
               "разрешения уполномоченного лица (п.9.2 ТЗ).\n\n")
    out.append(f"Всего полей: **{len(fields)}**.\n\n")

    for section in SECTION_ORDER:
        items = by_section.get(section)
        if not items:
            continue
        out.append(f"## {section}\n\n")
        out.append("| Код | Поле | Тип | Упрощённый | Полный | Кто заполняет "
                   "| Открыто | Валидация |\n")
        out.append("|---|---|---|---|---|---|---|---|\n")
        for item in items:
            out.append(
                f"| **{item['code']}** | {item['label']} | `{item['type_field']}` "
                f"| {REQUIRED_TITLES.get(item['required_simplified'], item['required_simplified'])} "
                f"| {REQUIRED_TITLES.get(item['required_full'], item['required_full'])} "
                f"| {item['filled_by']} | {item['public']} | {item['validation']} |\n"
            )
        out.append("\n")

    out.append("## Условно обязательные поля\n\n")
    out.append("Поле требуется, только если включён соответствующий признак. "
               "Признак T-02 (персональные данные, участие людей, этическое "
               "рассмотрение) сам по себе переводит проект на полный маршрут.\n\n")
    from app.domain.validation import CONDITIONAL_RULES

    out.append("| Признак | Что требуется дополнительно |\n|---|---|\n")
    for flag, column, message in CONDITIONAL_RULES:
        out.append(f"| `{flag}` | {message} |\n")
    out.append("| `publish_mode` = `project` или `all` | Публичная аннотация (A-04) |\n")
    out.append("| `route` = `full` | Основания полного маршрута (A-08) |\n\n")

    out.append("## Шесть обязательных научных полей\n\n")
    out.append("П.4.2 ТЗ требует для запуска упрощённого проекта «шесть "
               "обязательных научных полей», не перечисляя их. Приняты шесть полей "
               "раздела «Научное содержание», отвечающих принципу «Проверяемый "
               "результат» (п.2.3 ТЗ):\n\n")
    from app.domain.validation import SCIENTIFIC_CORE

    labels = {item["type_field"]: item["label"] for item in fields}
    codes = {item["type_field"]: item["code"] for item in fields}
    for i, column in enumerate(SCIENTIFIC_CORE, start=1):
        out.append(f"{i}. **{labels.get(column, column)}** ({codes.get(column, '')}, "
                   f"поле `{column}`)\n")
    out.append("\nПлановый тип результата (A-25) проверяется вместе с критериями "
               "результата (A-26) как один смысловой блок — «планируемый результат "
               "с критерием».\n\n")
    out.append("Набор вынесен в код (`domain/validation.py`) и потому может быть "
               "уточнён без выпуска новой версии приложения.\n")
    return "".join(out)


def roles_matrix_doc() -> str:
    from app.domain.taxonomy import (
        ACTIVE_STATUSES, DECISION_MATRIX, FULL_ROUTE_TITLES, RECOMMENDATIONS,
        REVIEW_BLOCKS, ROUTE_RULE, STATUSES,
    )

    out = [HEADER]
    out.append("# Матрица ролей, статусы и маршруты\n\n")
    out.append("Разделы 4 и 5 технического задания версии 1.0 от 06.10.2026, "
               "Приложения А, Б и В.\n\n")

    out.append("## Роли (п.4 ТЗ)\n\n")
    out.append("| Роль | Полномочия | Ограничения |\n|---|---|---|\n")
    out.append("| Ректор | Просмотр всего портфеля и панели ректора; решения по "
               "дополнительным ресурсам, внешним обязательствам, правовым и "
               "институциональным рискам | Не администрирует карточки |\n")
    out.append("| Научный совет | Квартальный обзор программ и портфеля; "
               "стратегические, спорные и исключительные случаи | Не согласовывает "
               "каждый стандартный проект |\n")
    out.append("| Проректор по науке | Владелец процесса; управление портфелем; "
               "запуск, приостановление и приёмка проектов полного маршрута; "
               "критические отклонения | При конфликте интересов замещается лицом, "
               "назначенным ректором |\n")
    out.append("| Секретарь Научного совета | Функциональное администрирование; "
               "проверка комплектности; сроки, напоминания, регистрация решений, "
               "панели и публикация разрешённых данных | Не оценивает научное "
               "содержание |\n")
    out.append("| Куратор программы | Паспорт программы; запуск и приёмка "
               "упрощённых проектов; рекомендации по полному маршруту; обзор "
               "программы | Не принимает решение по проекту, где имеет личную "
               "заинтересованность |\n")
    out.append("| Руководитель проекта | Карточка, команда, задачи, сроки, данные, "
               "риски и результаты; подтверждение вклада | Не эксперт и не "
               "принимающее лицо по собственному проекту |\n")
    out.append("| Участник | Порученные задачи, контрольные точки и "
               "подтверждающие материалы | Не меняет паспорт, маршрут и итоговое "
               "решение |\n")
    out.append("| Эксперт | Независимое структурированное заключение по "
               "назначенному объекту | Не редактирует карточку и не принимает "
               "управленческое решение |\n")
    out.append("| Технический администратор | Учётные записи, конфигурация, "
               "резервное копирование, обновления, интеграции и технический аудит "
               "| Не принимает научных решений |\n\n")

    out.append("### Внутрисистемная роль\n\n")
    out.append("`sysadmin` — системный администратор: учётные записи и настройки. "
               "Это техническая роль, её нет в перечне п.4 ТЗ, но без неё не "
               "кому создавать учётные записи.\n\n")

    out.append("### Совмещение ролей и конфликт интересов (п.4.1 ТЗ)\n\n")
    out.append("1. Один пользователь может иметь несколько ролей, но доступ "
               "проверяется также по его отношению к конкретному проекту.\n")
    out.append("2. Руководитель, участник, предполагаемый соавтор или научный "
               "руководитель участника **не может** проводить независимую "
               "экспертизу того же проекта.\n")
    out.append("3. При заинтересованности куратора решение переходит к проректору "
               "по науке; при заинтересованности проректора — к лицу, назначенному "
               "ректором.\n")
    out.append("4. Эксперт до доступа к закрытым материалам подтверждает отсутствие "
               "конфликта интересов либо заявляет самоотвод.\n")
    out.append("5. Общие учётные записи, в том числе учётная запись «Научный совет», "
               "**не допускаются**.\n")
    out.append("6. Факт отвода, замещения и основание фиксируются в журнале без "
               "возможности удаления.\n\n")

    out.append("## Матрица ключевых решений (п.4.2 ТЗ)\n\n")
    out.append("| Операция | Кто решает | Основание | Срок |\n|---|---|---|---|\n")
    for _, spec in DECISION_MATRIX.items():
        out.append(f"| {spec['title']} | **{spec['who']}** | {spec['basis']} "
                   f"| {spec['deadline']} |\n")
    out.append("\n")

    out.append("## Статусы (п.5.3 ТЗ)\n\n")
    out.append("| Код | Название | Содержание |\n|---|---|---|\n")
    for code, spec in STATUSES.items():
        out.append(f"| **{code}** | {spec['title']} | {spec['content']} |\n")
    out.append(f"\nАктивный портфель: {', '.join(ACTIVE_STATUSES)}.\n\n")

    out.append("## Маршруты и признаки (п.5.1 ТЗ)\n\n")
    out.append("| Маршрут | Когда применяется |\n|---|---|\n")
    out.append("| **Упрощённый** | Индивидуальная статья или малое исследование без "
               "признаков T-01…T-06 |\n")
    out.append("| **Полный** | Есть хотя бы один признак T-01…T-06 |\n\n")
    out.append("### Основания полного маршрута\n\n")
    out.append("| Код | Основание |\n|---|---|\n")
    for code, title in FULL_ROUTE_TITLES.items():
        out.append(f"| **{code}** | {title} |\n")
    out.append(f"\n> {ROUTE_RULE}\n\n")

    out.append("## Сроки обработки (п.5.5 ТЗ)\n\n")
    out.append("| Операция | Срок, рабочих дней |\n|---|---|\n")
    out.append("| Проверка комплектности | 3 |\n")
    out.append("| Принятие экспертом задания либо самоотвод | 1 |\n")
    out.append("| Предварительная или итоговая экспертиза | 10 |\n")
    out.append("| Решение по заключению | 5 |\n")
    out.append("| Реакция на жёлтый индикатор риска | 5 |\n")
    out.append("| Рассмотрение красного индикатора риска | 5 |\n\n")

    out.append("## Индикатор риска (п.5.4 ТЗ)\n\n")
    out.append("| Индикатор | Условие | Действие |\n|---|---|---|\n")
    out.append("| Зелёный | Работа идёт по плану; подтверждения актуальны | Сводное "
               "отображение без отдельного рассмотрения |\n")
    out.append("| Жёлтый | Нет подтверждения контрольной точки в срок; задержка до "
               "20 рабочих дней; проблемы с данными, качеством, командой или "
               "ресурсом | Руководитель за 5 рабочих дней указывает причину, меры и "
               "новый срок |\n")
    out.append("| Красный | Задержка более 20 рабочих дней, повторный срыв, отсутствие "
               "реакции, потеря данных или руководителя, необходимость изменить "
               "цель, высокий риск | Проректор рассматривает за 5 рабочих дней и может "
               "приостановить проект |\n\n")
    out.append("**Статус и индикатор риска — разные поля.** Проект может быть "
               "«Активен» и при этом иметь жёлтый индикатор.\n\n")

    out.append("## Краткое заключение эксперта (п.7.1 ТЗ)\n\n")
    out.append("Заключение содержит четыре обязательных блока и итоговую "
               "рекомендацию. После фиксации заключение не редактируется; "
               "исправление оформляется новой версией.\n\n")
    out.append("| Блок | Содержание |\n|---|---|\n")
    for _, title in REVIEW_BLOCKS:
        descriptions = {
            "Соответствие цели": "Связан ли вопрос с целью и заявленным результатом",
            "Метод и данные": "Достаточны ли метод, данные или доказательная логика",
            "Качество результата": "Подтверждён ли результат и соответствует ли критериям",
            "Риски и ограничения": "Есть ли условия, препятствующие запуску, "
                                   "публикации или применению",
        }
        out.append(f"| **{title}** | {descriptions.get(title, '')} |\n")
    out.append("\n| Рекомендация | Значение |\n|---|---|\n")
    for code, title in RECOMMENDATIONS.items():
        out.append(f"| `{code}` | {title} |\n")
    out.append("\nПриёмка возможна только по рекомендации «Поддержать» или "
               "«Поддержать с условиями».\n\n")

    out.append("## Переходы между статусами (Приложение Б ТЗ)\n\n")
    from app.domain.workflow import TRANSITIONS

    route_titles = {"simplified": "Б.1. Упрощённый маршрут",
                    "full": "Б.2. Полный маршрут"}
    actor_titles = {
        "secretary": "Секретарь", "prorector": "Проректор",
        "curator": "Куратор программы", "leader": "Руководитель",
    }
    for route, transitions in TRANSITIONS.items():
        out.append(f"### {route_titles[route]}\n\n")
        out.append("| Из статуса | Действие | В статус | Кто | Условие |\n")
        out.append("|---|---|---|---|---|\n")
        for t in transitions:
            actors = " или ".join(actor_titles.get(a, a) for a in t.actors)
            note = t.condition
            if t.reason_required:
                note += " (комментарий обязателен)"
            out.append(f"| {t.from_status} — {STATUSES[t.from_status]['title']} "
                       f"| **{t.title}** | {t.to_status} — {STATUSES[t.to_status]['title']} "
                       f"| {actors} | {note} |\n")
        out.append("\n")

    out.append("Действия, отсутствующие в матрице, блокируются с перечнем причин "
               "(FR-10). Интерфейс показывает причину блокировки, а не просто "
               "недоступную кнопку.\n")
    return "".join(out)


def main() -> int:
    DOCS.mkdir(exist_ok=True)
    (DOCS / "СЛОВАРЬ-ПОЛЕЙ.md").write_text(field_dictionary_doc(), encoding="utf-8")
    (DOCS / "МАТРИЦА-РОЛЕЙ.md").write_text(roles_matrix_doc(), encoding="utf-8")
    print("Создано: docs/СЛОВАРЬ-ПОЛЕЙ.md, docs/МАТРИЦА-РОЛЕЙ.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())